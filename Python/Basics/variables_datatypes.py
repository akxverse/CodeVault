# Variables and Data Types in Python
# Python automatically detects the data type

items = 25              # Integer
price = 199.99          # Float
product = "Laptop"      # String
in_stock = True         # Boolean

# Display values

print("Items:", items)
print("Price:", price)
print("Product:", product)
print("In Stock:", in_stock)

# Display data types

print("\nData Types:")
print(type(items))
print(type(price))
print(type(product))
print(type(in_stock))